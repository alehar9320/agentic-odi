"""Deterministic pull-request guardrails (issue #86).

The logic lives here, not in YAML, so every rule is unit-tested. The GitHub
workflow in ``.github/workflows/pr-guardrails.yml`` only gathers the diff and
calls this module.

Three deterministic gates (failures):
  * deletion budget - a PR may not delete a shipped file unless allowlisted
  * diff size       - a PR may not delete more than ``max_deletions`` lines
  * JSON block      - the machine-readable diff summary must match the diff

Two advisory gates (warnings):
  * body truth      - natural-language claims about files and tests
  * fabrication     - patterns that have shipped fabricated work before
  * branch freshness - a stale base is worth a rebase, not a block

Everything is computed on the cumulative ``base...HEAD`` diff, never per
commit. A tree-replacement commit buried in the middle of a branch stays
visible in the cumulative diff.
"""

from __future__ import annotations

import fnmatch
import json
import re
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path

# Files that are regenerated by design. Their churn is not a signal.
DEFAULT_GENERATED_EXCLUSIONS: tuple[str, ...] = (
    "uv.lock",
    "**/uv.lock",
    "package-lock.json",
    "**/package-lock.json",
    "yarn.lock",
    "**/yarn.lock",
    "pnpm-lock.yaml",
    "**/pnpm-lock.yaml",
    "Cargo.lock",
    "**/Cargo.lock",
    "poetry.lock",
    "**/poetry.lock",
    "*.lock",
    "openapi.json",
    "**/openapi.json",
    "schema.d.ts",
    "**/schema.d.ts",
    "coverage.xml",
    "**/coverage.xml",
)


@dataclass(frozen=True)
class GuardConfig:
    """Tunable thresholds, read from ``.github/pr-guardrails/config.yml``."""

    max_deletions: int = 500
    max_changed_files: int = 2000
    max_behind: int = 50
    tolerance: float = 0.20
    generated_exclusions: tuple[str, ...] = DEFAULT_GENERATED_EXCLUSIONS


@dataclass
class GuardResult:
    """Errors fail the build; warnings annotate the PR."""

    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def failed(self) -> bool:
        return bool(self.errors)


ReleaseLookup = Callable[[str], str | None]


def build_diff_args(base_ref: str, head_ref: str) -> list[str]:
    """The cumulative diff. Three dots = merge-base diff, not last-commit."""
    return ["git", "diff", "--name-status", f"{base_ref}...{head_ref}"]


def parse_name_status(output: str) -> list[tuple[str, str, str | None]]:
    """Parse ``git diff --name-status`` into (status, path, old_path) tuples."""
    entries: list[tuple[str, str, str | None]] = []
    for line in output.splitlines():
        if not line.strip():
            continue
        parts = line.split("\t")
        status = parts[0]
        if status.startswith("R") or status.startswith("C"):
            entries.append((status, parts[2], parts[1]))
        else:
            entries.append((status, parts[1], None))
    return entries


def parse_numstat(output: str) -> dict[str, tuple[int, int]]:
    """Parse ``git diff --numstat``; binary files count as (0, 0)."""
    stats: dict[str, tuple[int, int]] = {}
    for line in output.splitlines():
        if not line.strip():
            continue
        added, deleted, path = line.split("\t", 2)
        stats[path] = (0 if added == "-" else int(added), 0 if deleted == "-" else int(deleted))
    return stats


def changed_files_from_status(entries: Sequence[tuple[str, str, str | None]]) -> int:
    return len(entries)


def is_generated(path: str, config: GuardConfig) -> bool:
    return any(fnmatch.fnmatch(path, pattern) for pattern in config.generated_exclusions)


def _allowed(path: str, allowlist: Sequence[Mapping[str, object]]) -> bool:
    for entry in allowlist:
        pattern = str(entry.get("path", ""))
        if pattern and fnmatch.fnmatch(path, pattern):
            return True
    return False


def check_deletions(
    deleted: Sequence[str],
    allowlist: Sequence[Mapping[str, object]],
    release_lookup: ReleaseLookup,
) -> list[str]:
    """Fail every deletion that is not explicitly allowlisted."""
    errors: list[str] = []
    for path in deleted:
        if _allowed(path, allowlist):
            continue
        release = release_lookup(path)
        where = f"shipped in {release}" if release else "unreleased"
        errors.append(
            f"Deleted file {path!r} ({where}). Deleting a file that exists on the base "
            "branch is not allowed. If this is intentional, add an entry to "
            ".github/pr-guardrails/deletion-allowlist.yml naming the issue and reason."
        )
    return errors


def check_diff_budget(numstat: Mapping[str, tuple[int, int]], config: GuardConfig) -> list[str]:
    """Fail when the diff deletes too many lines or touches too many files."""
    counted = {path: stat for path, stat in numstat.items() if not is_generated(path, config)}
    deletions = sum(deleted for _added, deleted in counted.values())
    changed = len(counted)

    errors: list[str] = []
    if deletions > config.max_deletions:
        errors.append(
            f"The diff deletes {deletions} lines, over the {config.max_deletions}-line budget. "
            "Split the change, or add a generated-file exclusion for files that are "
            "regenerated by design."
        )
    if changed > config.max_changed_files:
        errors.append(
            f"The diff changes {changed} files, over the {config.max_changed_files}-file budget. "
            "Split the change."
        )
    return errors


def check_freshness(behind: int, config: GuardConfig) -> list[str]:
    """A stale base is a warning: rebases are best resolved by a human."""
    if behind > config.max_behind:
        return [
            f"This branch is {behind} commits behind the base branch "
            f"(limit {config.max_behind}). Rebase so the diff is computed against "
            "the current base."
        ]
    return []


def guard_diff_shape(
    *,
    deleted: Sequence[str],
    numstat: Mapping[str, tuple[int, int]],
    allowlist: Sequence[Mapping[str, object]],
    config: GuardConfig,
    release_lookup: ReleaseLookup,
    behind: int = 0,
) -> GuardResult:
    errors = check_deletions(deleted, allowlist, release_lookup)
    errors.extend(check_diff_budget(numstat, config))
    return GuardResult(errors=errors, warnings=check_freshness(behind, config))


def load_config(path: Path) -> GuardConfig:
    """Read ``config.yml``; a missing file keeps the defaults."""
    if not path.exists():
        return GuardConfig()
    import yaml

    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    defaults = GuardConfig()
    return GuardConfig(
        max_deletions=int(raw.get("max_deletions", defaults.max_deletions)),
        max_changed_files=int(raw.get("max_changed_files", defaults.max_changed_files)),
        max_behind=int(raw.get("max_behind", defaults.max_behind)),
        tolerance=float(raw.get("tolerance", defaults.tolerance)),
        generated_exclusions=tuple(raw.get("generated_exclusions", defaults.generated_exclusions)),
    )


def load_allowlist(path: Path) -> list[Mapping[str, object]]:
    """Read ``deletion-allowlist.yml``; a missing file denies every deletion."""
    if not path.exists():
        return []
    import yaml

    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or []
    if not isinstance(raw, list):
        raise ValueError(f"{path} must contain a list of deletion entries")
    return raw


# --- Body truth --------------------------------------------------------------

_JSON_BLOCK_RE = re.compile(r"```json\s*\n(.*?)```", re.DOTALL)
_FILE_CLAIM_RE = re.compile(r"(?i)\b(\d+)\+?\s+(?:source\s+)?files?\b")
_TEST_CLAIM_RE = re.compile(r"(?i)\b(\d+)\s+(?:total\s+)?tests?\s+(?:passing|pass|total|added)\b")
_TEST_TOTAL_RE = re.compile(r"(?i)\b(\d+)\s+total\s+tests\b")
_TITLE_CLAIM_RE = re.compile(
    r"(?i)\b(\d+)\s+(?:[\w-]+\s+){0,4}(?:micro-?improvements?|improvements?|features?|tests?)\b"
)
_NAMED_FILE_RE = re.compile(
    r"(?<![\w/.-])([\w./-]*[\w-]+\.(?:py|tsx?|jsx?|json|md|css|ya?ml|toml|rs|html|sh|txt))(?![\w])"
)
_NUMBERED_ROW_RE = re.compile(r"(?m)^\s*\d+[.)]\s+\S")
_FENCE_RE = re.compile(r"```.*?```", re.DOTALL)


def parse_json_block(body: str) -> dict[str, object] | None:
    """Return the first parseable ```json fenced block, or None."""
    for match in _JSON_BLOCK_RE.finditer(body):
        try:
            parsed = json.loads(match.group(1))
        except json.JSONDecodeError:
            continue
        if isinstance(parsed, dict):
            return parsed
    return None


def _within_tolerance(claimed: int, actual: int, tolerance: float) -> bool:
    if actual == 0:
        return claimed == 0
    return abs(claimed - actual) / abs(actual) <= tolerance


def check_json_block(
    block: Mapping[str, object],
    changed_files: int,
    tests_added: int,
    net_lines: int,
    tolerance: float,
) -> list[str]:
    """The machine-readable summary is deterministic, so a mismatch fails."""
    actuals = {
        "changed_files": changed_files,
        "tests_added": tests_added,
        "net_lines": net_lines,
    }
    errors: list[str] = []
    for key, actual in actuals.items():
        if key not in block:
            continue
        claimed = int(block[key])  # type: ignore[arg-type]
        if key == "net_lines":
            slack = max(10, int(abs(actual) * tolerance))
            matches = abs(claimed - actual) <= slack
        else:
            matches = _within_tolerance(claimed, actual, tolerance)
        if not matches:
            errors.append(
                f"The JSON diff summary claims {key}={claimed}, but the diff has {actual}. "
                "Update the fenced json block in the pull request body."
            )
    return errors


def _file_count_claims(body: str) -> list[int]:
    claims = [int(match) for match in _FILE_CLAIM_RE.findall(body)]
    if re.search(r"(?i)improvements?", body):
        rows = len(_NUMBERED_ROW_RE.findall(body))
        if rows:
            claims.append(rows)
    return claims


def _test_count_claims(body: str) -> list[int]:
    return [int(match) for match in _TEST_CLAIM_RE.findall(body)] + [
        int(match) for match in _TEST_TOTAL_RE.findall(body)
    ]


def _named_file_exists(named: str, candidate_paths: Sequence[str]) -> bool:
    for path in candidate_paths:
        if path == named or path.endswith("/" + named) or named.endswith("/" + path):
            return True
    return False


def _strip_fenced_blocks(text: str) -> str:
    """Verification commands and their output are not claims."""
    return _FENCE_RE.sub("", text)


def _body_truth_warnings(
    body: str,
    title: str,
    changed_files: int,
    tests_added: int,
    changed_paths: Sequence[str],
    base_paths: Sequence[str],
    tolerance: float,
) -> list[str]:
    warnings: list[str] = []

    for claim in _file_count_claims(body):
        if not _within_tolerance(claim, changed_files, tolerance):
            warnings.append(
                f"The pull request body claims {claim} files, but the diff changes "
                f"{changed_files}. Correct the description."
            )

    for claim in _test_count_claims(body):
        if not _within_tolerance(claim, tests_added, tolerance):
            warnings.append(
                f"The pull request body claims {claim} tests, but the diff adds "
                f"{tests_added} test functions. Correct the description."
            )

    for match in _TITLE_CLAIM_RE.findall(title):
        claim = int(match)
        if not _within_tolerance(claim, changed_files, tolerance):
            warnings.append(
                f"The pull request title claims {claim}, but the diff changes "
                f"{changed_files} files. Correct the title."
            )

    known = list(changed_paths) + list(base_paths)
    for named in {match for match in _NAMED_FILE_RE.findall(body)}:
        if not _named_file_exists(named, known):
            warnings.append(
                f"The pull request body names {named!r}, which is neither in the diff "
                "nor on the base branch."
            )

    return warnings


def check_body_truth(
    body: str,
    title: str,
    *,
    changed_files: int,
    tests_added: int,
    net_lines: int,
    changed_paths: Sequence[str],
    base_paths: Sequence[str],
    config: GuardConfig,
) -> GuardResult:
    """Natural-language claims warn; the JSON block fails on a mismatch."""
    warnings = _body_truth_warnings(
        _strip_fenced_blocks(body),
        title,
        changed_files,
        tests_added,
        changed_paths,
        base_paths,
        config.tolerance,
    )
    errors: list[str] = []
    block = parse_json_block(body)
    if block is not None:
        errors = check_json_block(block, changed_files, tests_added, net_lines, config.tolerance)
    return GuardResult(errors=errors, warnings=warnings)


# --- Fabrication guard -------------------------------------------------------

_MEASUREMENT_RE = re.compile(
    r"""["'][^"']*\b\d[\d,]*\s*(?:hours?|days?|minutes?|users?|customers?|dollars?|%|percent)\b[^"']*["']""",
    re.IGNORECASE,
)
_STUB_RE = re.compile(r"\b(?:TODO|FIXME)\b|NotImplementedError|pass\s+#\s*stub", re.IGNORECASE)


FABRICATION_IGNORE_PATHS = frozenset({"scripts/pr_guards.py"})


def _is_prose_path(path: str) -> bool:
    return path.endswith((".md", ".rst", ".txt"))


def _is_test_path(path: str) -> bool:
    parts = path.replace("\\", "/").split("/")
    name = parts[-1]
    return "tests" in parts or name.startswith("test_") or name.endswith("_test.py")


def check_fabrication(added_lines: Sequence[tuple[str, int, str]]) -> list[str]:
    """Warn on diff patterns that fabricated work in this repository's past.

    Warnings only: the word "mock" is legitimate in tests and prose, and a
    false positive must not block a build.
    """
    warnings: list[str] = []
    for path, lineno, text in added_lines:
        if _is_test_path(path) or _is_prose_path(path) or path in FABRICATION_IGNORE_PATHS:
            continue
        stripped = text.strip()

        if _STUB_RE.search(text):
            warnings.append(
                f"{path}:{lineno}: new TODO/FIXME/NotImplementedError/stub in the diff."
            )

        if _MEASUREMENT_RE.search(text):
            warnings.append(
                f"{path}:{lineno}: hardcoded measurement string in the diff; "
                "replace it with a real value or cite the source."
            )

        if (
            "mock" in text.lower()
            and ("return" in text or stripped.startswith("#") or '"""' in text)
            and any(quote in text for quote in ('"', "'"))
        ):
            warnings.append(
                f"{path}:{lineno}: 'mock' on a line that returns a value; "
                "confirm this is real behavior, not a fabrication."
            )

    warnings.extend(_unconditional_is_available(added_lines))
    return warnings


def _unconditional_is_available(added_lines: Sequence[tuple[str, int, str]]) -> list[str]:
    warnings: list[str] = []
    for index, (path, _lineno, text) in enumerate(added_lines):
        if (
            "def is_available" not in text
            or _is_test_path(path)
            or _is_prose_path(path)
            or path in FABRICATION_IGNORE_PATHS
        ):
            continue
        for later_path, later_line, later_text in added_lines[index + 1 : index + 4]:
            if later_path != path:
                break
            stripped = later_text.strip()
            if not stripped or stripped.startswith("#"):
                continue
            if stripped.startswith("return True"):
                warnings.append(
                    f"{path}:{later_line}: is_available always returns True, so it "
                    "reports a capability it has not checked."
                )
            break
    return warnings


# --- Diff scanning -----------------------------------------------------------

_HUNK_RE = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")


def parse_added_lines(diff: str) -> list[tuple[str, int, str]]:
    """Return ``(path, line_number, text)`` for every added line in a unified diff."""
    added: list[tuple[str, int, str]] = []
    path = ""
    lineno = 0
    for line in diff.splitlines():
        if line.startswith("+++ b/"):
            path = line[len("+++ b/") :]
            continue
        if line.startswith("--- ") or line.startswith("diff --git "):
            continue
        if line.startswith("@@"):
            match = _HUNK_RE.match(line)
            if match:
                lineno = int(match.group(1))
            continue
        if line.startswith("+"):
            added.append((path, lineno, line[1:]))
            lineno += 1
        elif line.startswith(" "):
            lineno += 1
    return added


_TEST_DEF_RE = re.compile(r"^\s*(?:def\s+test_|it\(|test\()")


def count_tests_added(added_lines: Sequence[tuple[str, int, str]]) -> int:
    """Count test functions added by the diff (Python or JS/TS)."""
    return sum(1 for _path, _line, text in added_lines if _TEST_DEF_RE.match(text))


# --- CLI ---------------------------------------------------------------------


def _git(*args: str) -> str:
    import subprocess

    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout


def _release_lookup(base_ref: str) -> ReleaseLookup:
    cache: dict[str, str | None] = {}

    def lookup(path: str) -> str | None:
        if path in cache:
            return cache[path]
        release: str | None = None
        try:
            sha = _git("log", "-1", "--format=%H", base_ref, "--", path).strip()
            if sha:
                tags = _git("tag", "--contains", sha, "--sort=v:refname").splitlines()
                release = tags[0] if tags else None
        except Exception:  # noqa: BLE001 - an unknown release is "unreleased"
            release = None
        cache[path] = release
        return release

    return lookup


def _collect(
    base_ref: str,
) -> tuple[list[tuple[str, str, str | None]], dict[str, tuple[int, int]], str]:
    args = build_diff_args(base_ref, "HEAD")
    status = parse_name_status(_git(*args[1:]))
    numstat = parse_numstat(_git("diff", "--numstat", f"{base_ref}...HEAD"))
    diff = _git("diff", "--unified=0", f"{base_ref}...HEAD")
    return status, numstat, diff


def _emit(kind: str, message: str) -> None:
    print(f"::{kind}::{message}")


def _write_warnings(path: str | None, warnings: Sequence[str]) -> None:
    if path:
        Path(path).write_text("\n".join(warnings) + ("\n" if warnings else ""), encoding="utf-8")


def _diff_shape(args: object) -> int:
    config = load_config(Path(args.config))  # type: ignore[attr-defined]
    allowlist = load_allowlist(Path(args.allowlist))  # type: ignore[attr-defined]
    base_ref = args.base_ref  # type: ignore[attr-defined]
    status, numstat, _diff = _collect(base_ref)
    deleted = [new for change, new, _old in status if change == "D"]
    behind = int(_git("rev-list", "--count", f"HEAD..{base_ref}").strip() or "0")
    result = guard_diff_shape(
        deleted=deleted,
        numstat=numstat,
        allowlist=allowlist,
        config=config,
        release_lookup=_release_lookup(base_ref),
        behind=behind,
    )
    for warning in result.warnings:
        _emit("warning", warning)
    for error in result.errors:
        _emit("error", error)
    if result.failed:
        print(f"pr-guardrails: {len(result.errors)} error(s)")
        return 1
    print("pr-guardrails: diff shape OK")
    return 0


def _body_truth(args: object) -> int:
    config = load_config(Path(args.config))  # type: ignore[attr-defined]
    base_ref = args.base_ref  # type: ignore[attr-defined]
    status, numstat, diff = _collect(base_ref)
    added = parse_added_lines(diff)
    counted = {path: stat for path, stat in numstat.items() if not is_generated(path, config)}
    net_lines = sum(added_lines - deleted_lines for added_lines, deleted_lines in counted.values())
    base_paths = _git("ls-tree", "-r", "--name-only", base_ref).splitlines()
    body = Path(args.body_file).read_text(encoding="utf-8")  # type: ignore[attr-defined]

    result = check_body_truth(
        body,
        args.title,  # type: ignore[attr-defined]
        changed_files=len(status),
        tests_added=count_tests_added(added),
        net_lines=net_lines,
        changed_paths=[new for _change, new, _old in status],
        base_paths=base_paths,
        config=config,
    )
    for warning in result.warnings:
        _emit("warning", warning)
    for error in result.errors:
        _emit("error", error)
    _write_warnings(args.warnings_out, result.warnings)  # type: ignore[attr-defined]
    if result.failed:
        print(f"pr-guardrails: {len(result.errors)} body-truth error(s)")
        return 1
    print("pr-guardrails: body truth OK")
    return 0


def _fabrication(args: object) -> int:
    base_ref = args.base_ref  # type: ignore[attr-defined]
    _status, _numstat, diff = _collect(base_ref)
    warnings = check_fabrication(parse_added_lines(diff))
    for warning in warnings:
        _emit("warning", warning)
    _write_warnings(args.warnings_out, warnings)  # type: ignore[attr-defined]
    print(f"pr-guardrails: {len(warnings)} fabrication warning(s)")
    return 0


def main(argv: Sequence[str] | None = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description="Deterministic pull request guardrails.")
    subparsers = parser.add_subparsers(dest="command", required=True)

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--base-ref", default="origin/main")
    common.add_argument("--config", default=".github/pr-guardrails/config.yml")
    common.add_argument("--allowlist", default=".github/pr-guardrails/deletion-allowlist.yml")

    subparsers.add_parser("diff-shape", parents=[common])

    body_parser = subparsers.add_parser("body-truth", parents=[common])
    body_parser.add_argument("--body-file", required=True)
    body_parser.add_argument("--title", default="")
    body_parser.add_argument("--warnings-out")

    fabrication_parser = subparsers.add_parser("fabrication", parents=[common])
    fabrication_parser.add_argument("--warnings-out")

    args = parser.parse_args(argv)
    if args.command == "diff-shape":
        return _diff_shape(args)
    if args.command == "body-truth":
        return _body_truth(args)
    return _fabrication(args)


if __name__ == "__main__":
    raise SystemExit(main())
