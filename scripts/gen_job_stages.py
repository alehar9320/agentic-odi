#!/usr/bin/env python3
"""Generate ``apps/studio/src/domain/jobStages.ts`` from the core stage constant.

The eight Universal Job Map stages decide when a job map is complete, and the
Studio renders those same eight. One list, in ``packages/core``; the TypeScript
side is generated so the two cannot drift. Run from anywhere:

    uv run python scripts/gen_job_stages.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from agentic_odi_core import job_stage_catalog

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "apps" / "studio" / "src" / "domain" / "jobStages.ts"

HEADER = """/**
 * Generated by scripts/gen_job_stages.py from ``agentic_odi_core.job_stage_catalog``.
 * Edit the Python constant, then regenerate; do not hand-edit this file.
 */

export interface JobStage {
  id: string;
  name: string;
  desc: string;
}

export const JOB_STAGES: JobStage[] = [
"""


def render() -> str:
    rows = "".join(
        f'  {{ id: "{stage["id"]}", name: "{stage["name"]}", desc: "{stage["desc"]}" }},\n'
        for stage in job_stage_catalog()
    )
    return f"{HEADER}{rows}];\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when the committed file is not what the core constant produces.",
    )
    args = parser.parse_args(argv)

    generated = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != generated:
            print(
                f"{TARGET} is stale; run `uv run python scripts/gen_job_stages.py`",
                file=sys.stderr,
            )
            return 1
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(generated, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
