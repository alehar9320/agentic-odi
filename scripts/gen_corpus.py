"""Write the deterministic reference study to a SQLite store.

The corpus is generated by :func:`agentic_odi_core.corpus.build_corpus`, so the
same arguments always produce the same records on any machine. This script only
chooses where to write them.

Usage:
    uv run python scripts/gen_corpus.py --out /tmp/corpus.db
    uv run python scripts/gen_corpus.py --out /tmp/corpus.db --outcomes 1500 --jobs 30

The store is written through the repository's own append path, so the file
replays exactly like a real workspace.
"""

from __future__ import annotations

import argparse
import sys

from agentic_odi_core.corpus import REFERENCE_JOBS, REFERENCE_OUTCOMES, build_corpus
from agentic_odi_core.sqlite_repository import SQLiteRepository


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, help="Path to the SQLite store to write.")
    parser.add_argument(
        "--outcomes",
        type=int,
        default=REFERENCE_OUTCOMES,
        help=f"Outcomes to generate (default {REFERENCE_OUTCOMES}).",
    )
    parser.add_argument(
        "--jobs",
        type=int,
        default=REFERENCE_JOBS,
        help=f"Jobs to generate (default {REFERENCE_JOBS}).",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    corpus = build_corpus(outcomes=args.outcomes, jobs=args.jobs)

    repo = SQLiteRepository(args.out)
    try:
        for job in corpus.jobs:
            repo.add_job(job)
        for step in corpus.steps:
            repo.add_step(step)
        for outcome in corpus.outcomes:
            repo.add_outcome(outcome)
        for record in corpus.evidence:
            repo.add_evidence(record)
    finally:
        repo.close()

    counts = corpus.counts()
    print(
        f"Wrote {counts['outcomes']} outcomes, {counts['jobs']} jobs, "
        f"{counts['steps']} steps, {counts['evidence']} evidence rows to {args.out}"
    )
    print(f"corpus digest: {corpus.digest()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
