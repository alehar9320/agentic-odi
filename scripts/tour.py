"""Generate the 90-second terminal tour from ``docs/tour/script.md``.

The tour is a recording of the real CLI, not a picture of it: every numbered step
in the script is executed here, in a throwaway workspace, and its captured output
becomes the cast. So a command that stops working fails this script rather than
surprising someone who is following the tour.

Nothing here reaches the network, a model, or a workspace that matters. The store
is the deterministic demo study from ``scripts/gen_corpus.py``, and the output is
scrubbed back to ``$TOUR_DB`` / ``$TOUR_OUT`` so two runs on two machines write the
same bytes.

Usage:
    uv run python scripts/tour.py --write
    uv run python scripts/tour.py --out /tmp/tour-check
"""

from __future__ import annotations

import argparse
import contextlib
import hashlib
import importlib.util
import io
import json
import re
import shlex
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import typer.testing

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "docs" / "tour"
SCRIPT = DEFAULT_OUT / "script.md"
ASSETS = ("tour.cast", "README.md", "manifest.json")

SAMPLE_LABEL = "Sample data: generated by scripts/gen_corpus.py, not real research."
PLAYBACK_BUDGET_SECONDS = 90

# Pinned pacing. The cast's event times and the README's playback figure both come
# from these constants, so the recorded length and the advertised length cannot
# disagree, and the recording is the same length on every machine.
INTRO_SECONDS = 2.0
TYPE_SECONDS = 0.35
HOLD_SECONDS = 4.0

CAST_TITLE = f"The agentic-odi loop in {PLAYBACK_BUDGET_SECONDS} seconds"
CAST_WIDTH = 90
CAST_HEIGHT = 24

STEP_HEADING = re.compile(r"^## (?P<number>\d+)\. (?P<title>[^#\n][^\n]*)$", re.MULTILINE)
FENCE = re.compile(r"^```bash\n(?P<body>.*?)^```", re.DOTALL | re.MULTILINE)
PROMPT = "tour$ "

LOCAL_ONLY = {
    "COLUMNS": str(CAST_WIDTH),
    "NO_COLOR": "1",
    "AGENTIC_ODI_BACKEND": "local",
}


class TourError(RuntimeError):
    """A step of the script did not run, or the script is malformed."""


@dataclass(frozen=True)
class Step:
    number: int
    title: str
    command: str
    output: str


def playback_seconds(steps: int) -> float:
    """The cast's running time, from the pinned pacing and the step count."""
    return INTRO_SECONDS + steps * (TYPE_SECONDS + HOLD_SECONDS)


def _parse(text: str) -> list[tuple[int, str, str]]:
    """(number, title, command) for every numbered section, in order."""
    headings = list(STEP_HEADING.finditer(text))
    found: list[tuple[int, str, str]] = []
    for index, heading in enumerate(headings):
        stop = headings[index + 1].start() if index + 1 < len(headings) else len(text)
        block = FENCE.search(text[heading.end() : stop])
        if block is None:
            raise TourError(f"step {heading['number']} has no ```bash block: {heading['title']}")
        lines = [line for line in block["body"].splitlines() if line.strip()]
        if len(lines) != 1:
            raise TourError(
                f"step {heading['number']} must hold exactly one command, found {len(lines)}"
            )
        found.append((int(heading["number"]), heading["title"].strip(), lines[0]))
    if not found:
        raise TourError(f"{SCRIPT} has no numbered steps")
    return found


def load_script(script: Path = SCRIPT) -> list[str]:
    """The tour's commands, one per numbered step, with placeholders intact."""
    return [command for _, _, command in _parse(script.read_text(encoding="utf-8"))]


def step_titles(script: Path = SCRIPT) -> list[str]:
    """The numbered section headings, so the README and the cast can name each step."""
    return [f"{number}. {title}" for number, title, _ in _parse(script.read_text(encoding="utf-8"))]


# --- execution ----------------------------------------------------------------


def _load_gen_corpus() -> Any:
    path = ROOT / "scripts" / "gen_corpus.py"
    spec = importlib.util.spec_from_file_location("tour_gen_corpus", path)
    if spec is None or spec.loader is None:
        raise TourError(f"cannot load the demo-study generator: {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _cli_app() -> Any:
    if str(ROOT / "apps" / "cli" / "src") not in sys.path:
        sys.path.insert(0, str(ROOT / "apps" / "cli" / "src"))
    from agentic_odi_cli.cli import app

    return app


def _expand(token: str, placeholders: list[tuple[str, str]]) -> str:
    for name, value in placeholders:
        token = token.replace(name, value)
    return token


def _run(command: str, paths: dict[str, str], db: Path) -> str:
    """Run one script command for real, and return what it printed."""
    # Longest placeholder first, because `$TOUR_WORKSPACE/…` contains the root that the
    # other two are derived from. Substituted as substrings so `$TOUR_OUT/study.json`
    # reaches the CLI as a real path rather than as a directory named `$TOUR_OUT`.
    placeholders = sorted(paths.items(), key=lambda pair: len(pair[0]), reverse=True)
    tokens = [_expand(token, placeholders) for token in shlex.split(command, posix=True)]
    if tokens[:2] == ["uv", "run"]:
        tokens = tokens[2:]
    buffer = io.StringIO()
    if tokens[:2] == ["python", "scripts/gen_corpus.py"]:
        with contextlib.redirect_stdout(buffer), contextlib.redirect_stderr(buffer):
            code = _load_gen_corpus().main(tokens[2:])
        if code != 0:
            raise TourError(f"the demo study failed to build (exit {code}): {command}")
        return buffer.getvalue()
    if not tokens or tokens[0] not in {"agentic-odi", "odi", "agentic-odi-cli"}:
        raise TourError(f"the tour only runs the CLI, not: {command}")
    result = typer.testing.CliRunner().invoke(
        _cli_app(), tokens[1:], env={**LOCAL_ONLY, "AGENTIC_ODI_DB": str(db)}
    )
    if result.exit_code != 0:
        printed = result.output.strip().splitlines()
        raise TourError(
            f"{command} exited {result.exit_code}: {printed[-1] if printed else 'no output'}"
        )
    return result.output


def capture(workspace: Path, script: Path = SCRIPT) -> list[Step]:
    """Execute every step of the script in a disposable workspace.

    Raises :class:`TourError` naming the first command that did not work, so a broken
    tour is reported rather than recorded.
    """
    workspace = Path(workspace)
    db = workspace / "tour.db"
    out = workspace / "out"
    out.mkdir(parents=True, exist_ok=True)
    paths = {
        "$TOUR_WORKSPACE": str(workspace),
        "$TOUR_DB": str(db),
        "$TOUR_OUT": str(out),
    }
    reverse = sorted(paths.items(), key=lambda pair: len(pair[1]), reverse=True)

    steps: list[Step] = []
    for number, title, command in _parse(script.read_text(encoding="utf-8")):
        try:
            output = _run(command, paths, db)
        except TourError as failure:
            raise TourError(f"step {number} failed — {failure}") from failure
        for placeholder, real in reverse:
            output = output.replace(real, placeholder)
        steps.append(Step(number, title, command, output))
    return steps


# --- artifacts ----------------------------------------------------------------


def _cast(steps: list[Step]) -> str:
    header = {
        "version": 2,
        "width": CAST_WIDTH,
        "height": CAST_HEIGHT,
        "title": f"{CAST_TITLE} — {SAMPLE_LABEL}",
        "timestamp": 0,
        "env": {"TERM": "xterm-256color", "SHELL": "/bin/bash"},
    }
    lines = [json.dumps(header, ensure_ascii=False)]

    def emit(at: float, text: str) -> None:
        lines.append(json.dumps([round(at, 2), "o", text], ensure_ascii=False))

    intro = (
        f"{CAST_TITLE}\r\n",
        f"{SAMPLE_LABEL} Nothing here is a real workspace.\r\n",
    )
    for index, text in enumerate(intro):
        emit(0.4 + index * 0.8, text)

    for index, step in enumerate(steps):
        window = INTRO_SECONDS + index * (TYPE_SECONDS + HOLD_SECONDS)
        typed = window + TYPE_SECONDS
        body = step.output.splitlines() or ["(no output)"]
        events = [f"{line}\r\n" for line in body]
        events[-1] += "\r\n"
        emit(typed, f"{PROMPT}{step.command}\r\n")
        for position, text in enumerate(events):
            emit(typed + HOLD_SECONDS * (position + 1) / len(events), text)
    return "\n".join(lines) + "\n"


def _readme(steps: list[Step]) -> str:
    walk = "\n".join(
        [f"{index}. **{step.title}** — `{step.command}`" for index, step in enumerate(steps, 1)]
    )
    shown = "\n".join([step.command for step in steps])
    return f"""# The {PLAYBACK_BUDGET_SECONDS}-second tour, as a terminal session

{SAMPLE_LABEL} No customer content appears here, and no workspace you care about is
touched: every command carries `--db`, and the export writes into a temporary directory.

Generated by `scripts/tour.py` from [`script.md`](script.md): every command below was
run, in order, against a throwaway store, and its real output is what the cast shows.
Do not hand-edit this file or `tour.cast` — change the script and regenerate:

```bash
uv run python scripts/tour.py --write
```

## Play it

```bash
asciinema play docs/tour/tour.cast
```

The recording runs **{playback_seconds(len(steps)):.2f} seconds** against a budget of
{PLAYBACK_BUDGET_SECONDS} seconds. Its pace comes from the pinned timings in
`scripts/tour.py`, not from the wall clock, so it is the same length on every machine.

## What happens, in order

{walk}

## Type it yourself

Set up the disposable workspace first, then run the steps in order — the same tour
without a recording.

```bash
export TOUR_WORKSPACE="$(mktemp -d)/tour"
export TOUR_DB="$TOUR_WORKSPACE/tour.db"
export TOUR_OUT="$TOUR_WORKSPACE/out"
mkdir -p "$TOUR_OUT"
```

```text
{shown}
```

The store comes from `scripts/gen_corpus.py`, which is deterministic: the job is always
`JOB-0000`, and every id in the tour resolves the same way on your machine.

## Where the terminal stops

The tour ends at the exported study because that is where the terminal ends. The
decision brief is rendered in the browser (`apps/studio/src/lib/brief.ts`), so it is
not in the terminal and does not appear in this recording; the annotated screenshots
of it belong to ALH-236. The same loop as a conversation is
[The Living Studio](../living-studio.md), and the reasoning behind every command is in
the numbered steps of [`script.md`](script.md).
"""


def _manifest(steps: list[Step], assets: dict[str, str]) -> str:
    manifest = {
        "generated_by": "scripts/tour.py",
        "script": "docs/tour/script.md",
        "sample_data": True,
        "steps": len(steps),
        "pacing": {
            "intro_seconds": INTRO_SECONDS,
            "type_seconds": TYPE_SECONDS,
            "hold_seconds_per_step": HOLD_SECONDS,
        },
        "playback_seconds": round(playback_seconds(len(steps)), 2),
        "playback_budget_seconds": PLAYBACK_BUDGET_SECONDS,
        "cast": {"width": CAST_WIDTH, "height": CAST_HEIGHT, "title": CAST_TITLE},
        "commands": [step.command for step in steps],
        "sha256": {
            name: hashlib.sha256(assets[name].encode("utf-8")).hexdigest()
            for name in ("README.md", "tour.cast")
        },
    }
    return json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def generate(workspace: Path, script: Path = SCRIPT) -> dict[str, str]:
    """Run the tour in `workspace` and return the three assets as text."""
    steps = capture(workspace, script)
    assets = {"tour.cast": _cast(steps), "README.md": _readme(steps)}
    assets["manifest.json"] = _manifest(steps, assets)
    return assets


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    target = parser.add_mutually_exclusive_group()
    target.add_argument(
        "--out", type=Path, help="Write the assets to this directory and leave the repo alone."
    )
    target.add_argument("--write", action="store_true", help="Overwrite the committed assets.")
    parser.add_argument(
        "--script",
        type=Path,
        default=SCRIPT,
        help="The step script to record (default docs/tour/script.md).",
    )
    args = parser.parse_args(argv)
    if not (args.out or args.write):
        parser.error("nothing to write: pass --write, or --out DIR")
    destination = args.out or DEFAULT_OUT

    # The store and the export always live in a temporary directory, never next to
    # the assets, so --write cannot leave a demo database inside docs/.
    with tempfile.TemporaryDirectory(prefix="agentic-odi-tour-") as workspace:
        try:
            assets = generate(Path(workspace), args.script)
        except TourError as failure:
            print(f"tour failed: {failure}", file=sys.stderr)
            print("the committed assets were left untouched", file=sys.stderr)
            return 1

    destination.mkdir(parents=True, exist_ok=True)
    for name, text in sorted(assets.items()):
        (destination / name).write_text(text, encoding="utf-8")
        print(f"wrote {destination / name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
