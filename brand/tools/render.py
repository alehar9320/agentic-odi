"""Regenerate every Odi mascot artifact.

    uv run python brand/tools/render.py            # write the artifacts
    uv run python brand/tools/render.py --check    # fail if anything drifted

The generator is the single source of truth. Nothing under ``brand/assets``,
``apps/studio/public``, or the two generated source files is ever hand-edited.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "brand" / "src"))

import odi_mascot  # noqa: E402

ASSETS = ROOT / "brand" / "assets"
STUDIO_PUBLIC = ROOT / "apps" / "studio" / "public"
STUDIO_COMPONENT = ROOT / "apps" / "studio" / "src" / "components" / "OdiMascot.tsx"
CLI_MODULE = ROOT / "apps" / "cli" / "src" / "agentic_odi_cli" / "mascot.py"

GENERATED_HEADER = "GENERATED by brand/tools/render.py - do not edit by hand."


def _studio_component() -> bytes:
    """Return the inline SVG React component for the studio brand mark."""
    svg = odi_mascot.render_svg_rle(odi_mascot.mark_raster())
    rects = re.findall(r"<rect [^>]*/>", svg)
    joined = "\n".join(f"      {rect}" for rect in rects)
    return f"""// {GENERATED_HEADER}
// Run `uv run python brand/tools/render.py` to regenerate.
export function OdiMascot({{
  size = 32,
  className,
}}: {{
  size?: number;
  className?: string;
}}) {{
  return (
    <svg
      width={{size}}
      height={{size}}
      viewBox="0 0 32 32"
      shapeRendering="crispEdges"
      role="presentation"
      aria-hidden="true"
      focusable="false"
      className={{className}}
    >
{joined}
    </svg>
  );
}}
""".encode()


def _cli_module() -> bytes:
    """Return the CLI banner module."""
    ascii_banner = odi_mascot.ascii_banner()
    ansi_banner = odi_mascot.ascii_banner_ansi()
    return f'''"""{GENERATED_HEADER}

Run `uv run python brand/tools/render.py` to regenerate.
"""

from __future__ import annotations

import os
import sys
from typing import Protocol

MASCOT_ASCII = {ascii_banner!r}

MASCOT_ANSI = {ansi_banner!r}


def render_banner(color: bool = True) -> str:
    """Return Odi's banner, coloured when asked for."""
    return MASCOT_ANSI if color else MASCOT_ASCII


class BannerStream(Protocol):
    """The part of a text stream the banner needs."""

    @property
    def encoding(self) -> str: ...

    def isatty(self) -> bool: ...


def should_show_banner(stream: BannerStream) -> bool:
    """Return True when the banner belongs on this stream.

    The banner is decoration: it is shown on a real terminal that can render
    the half-block glyphs, and omitted everywhere else so pipes and build logs
    stay clean. ``NO_COLOR`` keeps the banner but drops the colour.
    """
    if not stream.isatty():
        return False
    encoding = (getattr(stream, "encoding", "") or "").lower()
    return "utf" in encoding


def wants_color() -> bool:
    """Return True when the terminal should receive 24-bit colour."""
    return "NO_COLOR" not in os.environ and sys.stdout.isatty()
'''.encode()


def artifacts() -> dict[Path, bytes]:
    """Return every generated artifact, keyed by its path in the repository."""
    mark = odi_mascot.mark_raster()
    bust = odi_mascot.bust_raster()
    favicon_svg = odi_mascot.render_svg_rle(mark).encode()
    return {
        ASSETS / "odi-mascot.svg": odi_mascot.render_svg(bust, guides=True, rle=True).encode(),
        ASSETS / "odi-mark.svg": favicon_svg,
        ASSETS / "odi-mascot-256.png": odi_mascot.render_png(bust, 256),
        ASSETS / "odi-mascot-512.png": odi_mascot.render_png(bust, 512),
        ASSETS / "odi-mascot-1024.png": odi_mascot.render_png(bust, 1024),
        ASSETS / "odi-icon-1024.png": odi_mascot.render_png(mark, 1024),
        ASSETS / "favicon.svg": favicon_svg,
        ASSETS / "favicon.ico": odi_mascot.render_ico(),
        ASSETS / "apple-touch-icon.png": odi_mascot.render_png(mark, 180),
        ASSETS / "odi-ascii.txt": (odi_mascot.ascii_banner() + "\n").encode(),
        STUDIO_PUBLIC / "favicon.svg": favicon_svg,
        STUDIO_PUBLIC / "favicon.ico": odi_mascot.render_ico(),
        STUDIO_PUBLIC / "apple-touch-icon.png": odi_mascot.render_png(mark, 180),
        STUDIO_COMPONENT: _studio_component(),
        CLI_MODULE: _cli_module(),
    }


def main(argv: list[str] | None = None) -> int:
    """Write every artifact, or check the tree for drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail instead of writing when a committed artifact differs",
    )
    args = parser.parse_args(argv)

    drifted: list[Path] = []
    for path, payload in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_bytes() != payload:
                drifted.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)
        print(f"wrote {path.relative_to(ROOT)}")

    if drifted:
        print("These generated files are out of date:", file=sys.stderr)
        for path in drifted:
            print(f"  {path.relative_to(ROOT)}", file=sys.stderr)
        print("Run `uv run python brand/tools/render.py` to regenerate them.", file=sys.stderr)
        return 1
    if args.check:
        print("All generated Odi assets are up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
